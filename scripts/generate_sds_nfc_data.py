#!/usr/bin/env python3
"""Generate src/sds/nfc_data.h, the Unicode tables used by sds::text::to_nfc().

The tables are derived from Python's unicodedata module (the Unicode version is recorded in the
generated header). Re-run after a Python upgrade if a newer Unicode version is wanted:

    python3 scripts/generate_sds_nfc_data.py > src/sds/nfc_data.h
"""
import sys
import unicodedata

HANGUL_FIRST = 0xAC00
HANGUL_LAST = 0xD7A3


def canonical_decomposition(cp):
    text = unicodedata.decomposition(chr(cp))
    if not text or text.startswith("<"):
        return None
    return [int(part, 16) for part in text.split()]


def main():
    ccc_ranges = []
    decompositions = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ccc = unicodedata.combining(chr(cp))
        if ccc:
            if ccc_ranges and ccc_ranges[-1][1] == cp - 1 and ccc_ranges[-1][2] == ccc:
                ccc_ranges[-1][1] = cp
            else:
                ccc_ranges.append([cp, cp, ccc])
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        mapping = canonical_decomposition(cp)
        if mapping is None:
            continue
        if len(mapping) > 2:
            raise SystemExit(f"unexpected canonical decomposition length for U+{cp:04X}")
        first = mapping[0]
        second = mapping[1] if len(mapping) == 2 else 0
        # A pair is a primary composite only when NFC maps the character to itself; this
        # excludes singletons, non-starter decompositions and the composition exclusion table.
        composable = 1 if second and unicodedata.normalize("NFC", chr(cp)) == chr(cp) else 0
        decompositions.append((cp, first, second, composable))

    out = sys.stdout
    out.write("/**\n")
    out.write(" * @file src/sds/nfc_data.h\n")
    out.write(" * @brief Generated Unicode canonical decomposition and combining-class tables for NFC.\n")
    out.write(" *\n")
    out.write(f" * Generated by scripts/generate_sds_nfc_data.py from Unicode {unicodedata.unidata_version}. Do not edit.\n")
    out.write(" */\n")
    out.write("#pragma once\n\n")
    out.write("// standard includes\n#include <array>\n#include <cstdint>\n\n")
    out.write("namespace sds::text::nfc_data {\n")
    out.write("  /**\n   * @brief Inclusive code point range sharing one non-zero canonical combining class.\n   */\n")
    out.write("  struct ccc_range_t {\n")
    out.write("    std::uint32_t first;  ///< First code point of the range.\n")
    out.write("    std::uint32_t last;  ///< Last code point of the range.\n")
    out.write("    std::uint8_t ccc;  ///< Canonical combining class.\n")
    out.write("  };\n\n")
    out.write("  /**\n   * @brief One-level canonical decomposition of a code point.\n   */\n")
    out.write("  struct decomposition_t {\n")
    out.write("    std::uint32_t code_point;  ///< Decomposable code point.\n")
    out.write("    std::uint32_t first;  ///< First code point of the mapping.\n")
    out.write("    std::uint32_t second;  ///< Second code point of the mapping, or zero for a singleton.\n")
    out.write("    std::uint8_t composable;  ///< Non-zero when the pair recomposes to code_point under NFC.\n")
    out.write("  };\n\n")
    out.write(f"  inline constexpr std::array<ccc_range_t, {len(ccc_ranges)}> ccc_ranges {{{{\n")
    for first, last, ccc in ccc_ranges:
        out.write(f"    {{0x{first:X}, 0x{last:X}, {ccc}}},\n")
    out.write("  }};  ///< Sorted non-zero canonical combining classes.\n\n")
    out.write(f"  inline constexpr std::array<decomposition_t, {len(decompositions)}> decompositions {{{{\n")
    for cp, first, second, composable in decompositions:
        out.write(f"    {{0x{cp:X}, 0x{first:X}, 0x{second:X}, {composable}}},\n")
    out.write("  }};  ///< Canonical decompositions sorted by code point (Hangul syllables are algorithmic).\n")
    out.write("}  // namespace sds::text::nfc_data\n")


if __name__ == "__main__":
    main()
